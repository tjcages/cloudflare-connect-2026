export type LibraryColor = {
  label: string;
  hex: string;
};

export type LibraryGroup = {
  name: string;
  colors: LibraryColor[];
};

function srgbGamma(value: number): number {
  const v = value <= 0.0031308 ? 12.92 * value : 1.055 * value ** (1 / 2.4) - 0.055;
  return Math.min(1, Math.max(0, v));
}

function channelHex(value: number): string {
  return Math.round(value * 255)
    .toString(16)
    .padStart(2, "0");
}

function oklchToHex(l: number, c: number, hDeg: number): string {
  const h = (hDeg * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);

  const l_ = l + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = l - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = l - 0.0894841775 * a - 1.291485548 * b;

  const lLin = l_ ** 3;
  const mLin = m_ ** 3;
  const sLin = s_ ** 3;

  const r = 4.0767416621 * lLin - 3.3077115913 * mLin + 0.2309699292 * sLin;
  const g = -1.2684380046 * lLin + 2.6097574011 * mLin - 0.3413193965 * sLin;
  const bl = -0.0041960863 * lLin - 0.7034186147 * mLin + 1.707614701 * sLin;

  return `#${channelHex(srgbGamma(r))}${channelHex(srgbGamma(g))}${channelHex(srgbGamma(bl))}`;
}

type OklchStep = [label: string, l: number, c: number, h: number];

function oklchGroup(name: string, steps: OklchStep[]): LibraryGroup {
  return {
    name,
    colors: steps.map(([label, l, c, h]) => ({ label, hex: oklchToHex(l, c, h) })),
  };
}

