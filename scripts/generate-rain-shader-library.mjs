// Vendors the lab's shader library (apps/lab/src/shaderLibrary) into the site
// so the Hero Rain panel can offer the same texture-source presets. Only
// standalone Shadertoy-style `mainImage` GLSL survives the trip: Spiral and
// Comet Logo are three.js renderers, Twizzler Map is generated from live
// Canvas2D geometry, and Twizzler Sine needs ~30 lab-driven uniforms — none of
// those can run in the shared worker's GLSL wrapper.
//
// Usage: node scripts/generate-rain-shader-library.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const savedDir = join(root, "apps/lab/src/shaderLibrary/saved");
const outFile = join(
  root,
  "apps/site/src/components/_pages/connect/hero/rain-shader-library.ts"
);

function extractTemplateLiteral(file, constName) {
  const text = readFileSync(join(root, file), "utf8");
  const marker = `export const ${constName} = \``;
  const start = text.indexOf(marker);
  if (start === -1) throw new Error(`${constName} not found in ${file}`);
  const from = start + marker.length;
  const end = text.indexOf("`;", from);
  if (end === -1) throw new Error(`${constName} literal not closed in ${file}`);
  const literal = text.slice(from, end);
  if (literal.includes("${"))
    throw new Error(`${constName} contains interpolation; cannot vendor`);
  return literal;
}

const builtins = [
  {
    id: "connect",
    label: "Connect",
    source: extractTemplateLiteral(
      "apps/lab/src/connectShaderTextureSource.ts",
      "CONNECT_SHADER_TEXTURE_SOURCE"
    ),
  },
  {
    id: "nebula",
    label: "Nebula",
    source: extractTemplateLiteral(
      "apps/lab/src/defaultShaderTextureSource.ts",
      "DEFAULT_SHADER_TEXTURE_SOURCE"
    ),
  },
];

const saved = readdirSync(savedDir)
  .filter((name) => name.endsWith(".json"))
  .map((name) => JSON.parse(readFileSync(join(savedDir, name), "utf8")))
  .map((entry) => ({
    id: String(entry.id ?? "").trim(),
    label: String(entry.label ?? "").trim(),
    source: String(entry.source ?? ""),
  }))
  .filter((entry) => entry.id && entry.label && entry.source.trim())
  .sort(
    (a, b) => a.label.localeCompare(b.label) || a.id.localeCompare(b.id)
  );

const entries = [...builtins, ...saved];

const body = entries
  .map(
    (entry) =>
      `  {\n    id: ${JSON.stringify(entry.id)},\n    label: ${JSON.stringify(
        entry.label
      )},\n    source: ${JSON.stringify(entry.source)},\n  },`
  )
  .join("\n");

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-rain-shader-library.mjs — do not edit.
// Vendored from apps/lab/src/shaderLibrary (Connect + Nebula builtins and the
// saved Shadertoy-style presets). Spiral, Comet Logo, Twizzler Map and
// Twizzler Sine are renderer-/geometry-bound in the lab and cannot run in the
// shared worker's standalone GLSL wrapper, so they are excluded.

export type RainShaderLibraryEntry = {
  id: string;
  label: string;
  source: string;
};

export const RAIN_SHADER_LIBRARY: readonly RainShaderLibraryEntry[] = [
${body}
];

export function findRainShaderEntry(
  id: string
): RainShaderLibraryEntry | undefined {
  return RAIN_SHADER_LIBRARY.find((entry) => entry.id === id);
}

// Comment- and whitespace-insensitive so an entry still matches after
// cosmetic edits (the hero's default corridor ships comment-stripped).
function fingerprint(source: string): string {
  return source
    .replace(/\\/\\*[^]*?\\*\\//g, "")
    .replace(/\\/\\/[^\\n]*/g, "")
    .replace(/\\s+/g, "");
}

const FINGERPRINTS = new Map(
  RAIN_SHADER_LIBRARY.map((entry) => [fingerprint(entry.source), entry])
);

/** Match applied GLSL back to a library entry, e.g. to label the preset select. */
export function matchRainShaderEntry(
  source: string
): RainShaderLibraryEntry | undefined {
  return FINGERPRINTS.get(fingerprint(source));
}
`
);

console.log(`Wrote ${entries.length} entries to ${outFile}`);
